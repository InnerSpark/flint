/**
 * dist/brands.css (ASDS-86): every brand's variables under [data-brand="<name>"], so docs and
 * design reviews can show brands side by side, nested in either mode. Built from each brand's
 * own tokens.css, so it can't drift from what apps ship. Apps import their brand's tokens.css
 * instead; this file carries all four palettes.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { BRANDS, distFor } from './layers.mjs';

const blocks = (css) => [...css.matchAll(/^([^\s/{][^{]*?)\s*\{\n([\s\S]*?)\n\}/gm)].map((m) => ({ sel: m[1].trim(), body: m[2] }));

const out = ['/* GENERATED by scripts/build-brand-preview.mjs. Flint brand preview: set data-brand on any element. Do not edit by hand. */'];
for (const brand of BRANDS) {
  const B = `[data-brand="${brand}"]`;
  const rewrite = {
    ':root': B,
    '[data-theme="dark"]': `${B}[data-theme="dark"], [data-theme="dark"] ${B}, ${B} [data-theme="dark"]`,
    '[data-theme="light"]': `${B}[data-theme="light"], ${B} [data-theme="light"]`,
    ':root, [data-theme], [data-platform]': `${B}, ${B} [data-theme], ${B} [data-platform]`,
  };
  const css = readFileSync(join(distFor(brand), 'tokens.css'), 'utf8');
  const found = blocks(css);
  for (const sel of Object.keys(rewrite)) if (!found.some((b) => b.sel === sel)) throw new Error(`brand preview: ${brand}/tokens.css has no "${sel}" block`);
  out.push(`\n/* ---------- ${brand} ---------- */`);
  for (const { sel, body } of found) if (rewrite[sel]) out.push(`${rewrite[sel]} {\n${body}\n}`);
}
writeFileSync(join(distFor('flint'), 'brands.css'), out.join('\n') + '\n');
console.log(`Wrote dist/brands.css (${BRANDS.join(', ')}).`);
